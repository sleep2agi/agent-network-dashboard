import { chromium, devices } from 'playwright';
import { readFileSync } from 'node:fs';
const TOKEN = JSON.parse(readFileSync('/home/vansin/.anet/config.json', 'utf8')).token;
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ ...devices['iPhone 13'] });
await ctx.addCookies([{ name: 'anet_dashboard_session', value: `v3:${TOKEN}`, domain: '127.0.0.1', path: '/' }]);
const page = await ctx.newPage();
await page.goto('http://127.0.0.1:3000/', { waitUntil: 'domcontentloaded', timeout: 20000 });
await page.waitForTimeout(3500);
const overviewStrip = await page.locator('.anet-stat-strip').innerText();
await page.screenshot({ path: '/tmp/anet-mobile-qa/f2-overview.png', animations: 'disabled' });
await page.goto('http://127.0.0.1:3000/admin', { waitUntil: 'domcontentloaded', timeout: 20000 });
await page.waitForTimeout(3000);
const adminOnline = await page.locator('text=/Online Sessions/').innerText().catch(() => 'n/a');
await page.goto('http://127.0.0.1:3000/nodes', { waitUntil: 'domcontentloaded', timeout: 20000 });
await page.waitForTimeout(3000);
const nodesChip = await page.locator('text=/online/').first().innerText().catch(() => 'n/a');
console.log('Overview strip:', overviewStrip.replace(/\n/g, ' · '));
console.log('Admin:', adminOnline, '| Nodes chip:', nodesChip);
await browser.close();
