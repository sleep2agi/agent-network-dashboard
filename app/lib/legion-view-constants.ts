/**
 * 军团两页的「规模阈值」—— 2D 和 3D 必须用同一套数字。
 *
 * 为什么单独放一个文件：这几轮调阈值时，2D 用的是「60 人以内显示姓名」，
 * 3D 用的是「>80 节点降一档、>250 再降一档」，散落在两个组件里；一旦有人只改
 * 一边，两页对同一个网络的行为就不一致（同一个 100 人网络，3D 显示名字、2D 不显示）。
 */

/** 成员姓名 / 成员列表直接展示的最大人数；超过就只给缩略（点/首字母/搜索）。
 *  8 个部门 24 人的实测里 60 太大：名字互相压住，缩到 16 后靠悬停/选中/放大再出名字。 */
export const LEGION_LABEL_PEOPLE = 16;

/** 节点数超过这个值：开始降特效（标签预算、数据包抽稀、光晕只给高亮）。 */
export const LEGION_HEAVY_NODES = 80;

/** 节点数超过这个值：再降一档（低分辨率交互、只列部门、闭掉链路数据包等）。 */
export const LEGION_HUGE_NODES = 250;
